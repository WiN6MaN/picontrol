#!/usr/bin/env bash
# Pi Control installer. / Installateur de Pi Control.
#
# Usage: sudo ./install.sh [--dry-run] [--skip-deps] [--no-retroarch-config] [--no-autostart] [--user NAME]
# Idempotent: running it again updates the code and leaves your configuration alone.
# Idempotent : relancer le script met le code à jour sans toucher à votre configuration.
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/common.sh
. "$SRC_DIR/scripts/common.sh"

SKIP_DEPS=0
NO_RETROARCH=0
NO_AUTOSTART=0

usage() {
  cat <<'USAGE'
Usage: sudo ./install.sh [options]
  --dry-run               show what would be done, change nothing / afficher sans rien modifier
  --skip-deps             do not install python3-rpi.gpio / ne pas installer python3-rpi.gpio
  --no-retroarch-config   do not touch retroarch.cfg / ne pas modifier retroarch.cfg
  --no-autostart          do not touch autostart.sh / ne pas modifier autostart.sh
  --user NAME             user that runs RetroPie (default: $SUDO_USER or pi) / utilisateur de RetroPie
  -h, --help              this help / cette aide
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --skip-deps) SKIP_DEPS=1 ;;
    --no-retroarch-config) NO_RETROARCH=1 ;;
    --no-autostart) NO_AUTOSTART=1 ;;
    --user) shift; [ $# -gt 0 ] || die "--user needs a name"; RUN_USER=$1 ;;
    -h|--help) usage; exit 0 ;;
    *) parse_common_flag "$1" || { usage >&2; die "unknown option: $1"; } ;;
  esac
  shift
done

check_python() {
  command -v python3 >/dev/null 2>&1 || die "python3 not found"
  python3 -c 'import sys; sys.exit(sys.version_info < (3, 7))' || die "Python 3.7 or newer is required"
}

install_deps() {
  [ "$SKIP_DEPS" = 1 ] && return 0
  if python3 -c 'import RPi.GPIO' >/dev/null 2>&1; then
    say "RPi.GPIO already installed"
  else
    say "Installing python3-rpi.gpio"
    run apt-get install -y python3-rpi.gpio
  fi
}

install_code() {
  say "Installing the code to $PREFIX"
  run mkdir -p "$PREFIX/lib" "$BIN_DIR"
  run rm -rf "$PREFIX/lib/picontrol"
  run cp -r "$SRC_DIR/src/picontrol" "$PREFIX/lib/picontrol"
  run find "$PREFIX/lib/picontrol" -name __pycache__ -type d -prune -exec rm -rf {} +
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] write the launcher $BIN_DIR/picontrol"
    return 0
  fi
  {
    printf '#!/bin/sh\n# Generated by the Pi Control installer.\n'
    if [ "$ETC_DIR" != /etc/picontrol ]; then
      # shellcheck disable=SC2016  # the ${...} must stay literal in the generated launcher
      printf 'PICONTROL_CONFIG="${PICONTROL_CONFIG:-%s/picontrol.conf}"; export PICONTROL_CONFIG\n' "$ETC_DIR"
    fi
    # shellcheck disable=SC2016  # the ${...} must stay literal in the generated launcher
    printf 'PYTHONPATH="%s/lib${PYTHONPATH:+:$PYTHONPATH}" exec python3 -m picontrol "$@"\n' "$PREFIX"
  } > "$BIN_DIR/picontrol"
  chmod 755 "$BIN_DIR/picontrol"
}

install_config() {
  run mkdir -p "$ETC_DIR"
  if [ -f "$ETC_DIR/picontrol.conf" ]; then
    say "Keeping your configuration $ETC_DIR/picontrol.conf (new defaults: picontrol.conf.dist)"
  else
    say "Creating $ETC_DIR/picontrol.conf"
    run cp "$SRC_DIR/config/picontrol.conf" "$ETC_DIR/picontrol.conf"
  fi
  run cp "$SRC_DIR/config/picontrol.conf" "$ETC_DIR/picontrol.conf.dist"
}

# The web interface saves settings and the password hash here, so the RetroPie user owns the folder.
own_config_dir() {
  if [ "$(id -u)" -eq 0 ] && id "$RUN_USER" >/dev/null 2>&1; then
    run chown -R "$RUN_USER" "$ETC_DIR"
  fi
}

prepare_log() {
  run touch "$LOG_FILE"
  if [ "$(id -u)" -eq 0 ] && id "$RUN_USER" >/dev/null 2>&1; then
    run chown "$RUN_USER" "$LOG_FILE"
  fi
}

# set_cfg_option FILE KEY VALUE: make `KEY = "VALUE"` the single active setting in a RetroArch config.
set_cfg_option() {
  local file=$1 key=$2 value=$3 tmp
  if [ ! -f "$file" ]; then
    warn "$file not found: set $key = \"$value\" yourself"
    return 0
  fi
  if grep -Eq "^[[:space:]]*${key}[[:space:]]*=[[:space:]]*\"?${value}\"?[[:space:]]*\$" "$file"; then
    say "$key is already $value"
    return 0
  fi
  say "Setting $key = \"$value\" in $file"
  backup_once "$file"
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] edit $file"
    return 0
  fi
  tmp=$(mktemp)
  awk -v key="$key" -v line="$key = \"$value\"" '
    $0 ~ "^[ \t]*#?[ \t]*" key "[ \t]*=" { if (!done) { print line; done = 1 } next }
    { print }
    END { if (!done) print line }
  ' "$file" > "$tmp"
  cat "$tmp" > "$file"
  rm -f "$tmp"
}

install_autostart() {
  local block tmp
  if [ ! -f "$AUTOSTART" ]; then
    die "$AUTOSTART not found. Is this RetroPie? Use --no-autostart and see docs/en/installation.md"
  fi
  if ! grep -Eq '^[[:space:]]*emulationstation' "$AUTOSTART"; then
    die "no 'emulationstation' line in $AUTOSTART: add the block by hand (docs/en/installation.md)"
  fi
  say "Adding the start-up block to $AUTOSTART"
  backup_once "$AUTOSTART"
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] insert the picontrol block before the emulationstation line"
    return 0
  fi
  remove_block "$AUTOSTART"
  block=$(mktemp)
  tmp=$(mktemp)
  {
    printf '%s\n' "$BEGIN_MARK"
    printf '# Added by the Pi Control installer. Remove with uninstall.sh; do not edit between the markers.\n'
    printf '(while true; do %s/picontrol run; sleep 3; done) &\n' "$BIN_DIR"
    printf '%s\n' "$END_MARK"
  } > "$block"
  awk -v blockfile="$block" '
    BEGIN { while ((getline l < blockfile) > 0) text = text l "\n" }
    /^[ \t]*emulationstation/ && !done { printf "%s", text; done = 1 }
    { print }
    END { if (!done) exit 3 }
  ' "$AUTOSTART" > "$tmp" || die "could not insert the block into $AUTOSTART"
  cat "$tmp" > "$AUTOSTART"
  rm -f "$block" "$tmp"
}

need_root
check_python
install_deps
install_code
install_config
own_config_dir
prepare_log
if [ "$NO_RETROARCH" = 1 ]; then
  say "Skipping retroarch.cfg"
else
  set_cfg_option "$RETROARCH_CFG" network_cmd_enable true
  set_cfg_option "$RETROARCH_CFG" network_cmd_port 55355
fi
if [ "$NO_AUTOSTART" = 1 ]; then
  say "Skipping autostart.sh"
else
  install_autostart
fi

say ""
say "Done. Next steps / Étapes suivantes :"
say "  picontrol doctor            # check the installation / vérifier l'installation"
say "  picontrol test buttons      # then: led, fan, nfc / puis : led, fan, nfc"
say "  sudo reboot"
